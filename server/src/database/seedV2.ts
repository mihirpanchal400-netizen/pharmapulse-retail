/** Common Indian pharma trade schemes. */
const SCHEMES: { buy: number; free: number; weight: number }[] = [
  { buy: 0, free: 0, weight: 40 },
  { buy: 10, free: 1, weight: 22 },
  { buy: 20, free: 2, weight: 12 },
  { buy: 5, free: 1, weight: 8 },
  { buy: 10, free: 2, weight: 6 },
  { buy: 12, free: 1, weight: 5 },
  { buy: 25, free: 5, weight: 4 },
  { buy: 6, free: 1, weight: 3 },
];

function pickScheme(): { buy: number; free: number } {
  const total = SCHEMES.reduce((s, x) => s + x.weight, 0);
  let roll = rand() * total;
  for (const scheme of SCHEMES) {
    roll -= scheme.weight;
    if (roll <= 0) return { buy: scheme.buy, free: scheme.free };
  }
  return { buy: 0, free: 0 };
}

/** Synthetic GSTIN-shaped string. Format only — not a valid registration. */
function demoGstin(): string {
  const letters = 'ABCDEFGHIJKLMNPQRSTUVWXYZ';
  const four = Array.from({ length: 5 }, () => letters[intBetween(0, letters.length - 1)]).join('');
  return `27${four}${intBetween(1000, 9999)}${letters[intBetween(0, 25)]}1Z${intBetween(0, 9)}`;
}

function demoDrugLicense(): string {
  return `MH-${intBetween(10, 49)}-${intBetween(100000, 999999)}`;
}

