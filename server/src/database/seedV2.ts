export function seedV2(): void {
  const started = Date.now();
  const db = getDb();
  runMigrations(db);

  const admin = db.prepare("SELECT id FROM users WHERE role = 'ADMIN' LIMIT 1").get() as
    | { id: number }
    | undefined;
  const adminId = admin?.id ?? 1;

  const productCount = (db.prepare('SELECT COUNT(*) AS n FROM products').get() as { n: number }).n;
  if (productCount === 0) {
    throw new Error('No products found. Run  npm run seed  first to create the base dataset.');
  }

  console.log('  Clearing existing procurement data...');
  clearV2Data();

  console.log('  Creating manufacturer master...');
  seedManufacturers();

  console.log(`  Creating ${DISTRIBUTOR_NAMES.length} demo distributors...`);
  const distributorIds = seedDistributors();

  console.log('  Building distributor catalogues (prices, schemes, availability)...');
  const catalogueLines = seedCatalogues(distributorIds);

  console.log('  Generating purchase order history...');
  const po = seedPurchaseOrders(adminId);

  console.log('  Marking institutional credit sales...');
  const creditSales = seedCustomerCredit();

  logActivity({
    userId: adminId,
    username: 'admin',
    action: 'SEED',
    module: 'SETTINGS',
    summary: 'Generated demo distributor network and procurement history',
  });

  // Pharmacy location, used by distributor discovery.
  const settings = db.prepare('INSERT OR IGNORE INTO settings (key, value) VALUES (?, ?)');
  db.transaction(() => {
    settings.run('pharmacy_city', 'Pune');
    settings.run('pharmacy_area', 'MG Road');
    settings.run('pharmacy_pin', '411001');
    settings.run('pharmacy_state', 'Maharashtra');
  })();

  const stats = db
    .prepare(
      `SELECT (SELECT COUNT(*) FROM manufacturers)         AS manufacturers,
              (SELECT COUNT(*) FROM distributors)          AS distributors,
              (SELECT COUNT(*) FROM distributor_products)  AS catalogue,
              (SELECT COUNT(*) FROM purchase_orders)       AS pos,
              (SELECT COUNT(*) FROM supplier_invoices)     AS invoices,
              (SELECT COUNT(*) FROM supplier_payments)     AS payments,
              (SELECT COALESCE(SUM(invoice_amount - paid_amount),0) FROM supplier_invoices
                WHERE status <> 'PAID')                    AS outstanding,
              (SELECT COALESCE(SUM(total - paid_amount),0) FROM sales
                WHERE total > paid_amount)                 AS custOutstanding`,
    )
    .get() as Record<string, number>;

  console.log('');
  console.log('  Demo procurement network created');
  console.log('  ------------------------------------------------');
  console.log(`  Manufacturers          ${stats.manufacturers}`);
  console.log(`  Distributors           ${stats.distributors}`);
  console.log(`  Catalogue lines        ${stats.catalogue.toLocaleString('en-IN')} (${catalogueLines} generated)`);
  console.log(`  Purchase orders        ${stats.pos}  (${po.received} received)`);
  console.log(`  Supplier invoices      ${stats.invoices}`);
  console.log(`  Supplier payments      ${stats.payments}`);
  console.log(`  Supplier outstanding   ${round2(stats.outstanding).toLocaleString('en-IN')}`);
  console.log(`  Credit sales           ${creditSales} (customer outstanding ${round2(stats.custOutstanding).toLocaleString('en-IN')})`);
  console.log(`  Generated in           ${((Date.now() - started) / 1000).toFixed(1)}s (seed ${SEED})`);
  console.log('');
  console.log('  NOTE: every distributor, price, scheme and stock figure above is');
  console.log('  synthetic demo data generated locally. No external platform is involved.');
  console.log('');
}

if (require.main === module) {
  try {
    seedV2();
    closeDb();
  } catch (err) {
    console.error('\n  Procurement seeding failed:', err instanceof Error ? err.message : err);
    closeDb();
    process.exit(1);
  }
}
