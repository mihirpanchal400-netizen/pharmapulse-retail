/**
 * Builds each distributor's catalogue.
 *
 * Not every distributor carries every product - that is what makes supplier
 * comparison meaningful. Prices vary by a few percent around the product's PTR
 * and schemes are drawn from the weighted table, so the cheapest headline rate
 * is frequently NOT the cheapest effective cost. That tension is the whole
 * point of the comparison screen.
 */
function seedCatalogues(distributorIds: number[]): number {
  const db = getDb();
  const products = db.prepare('SELECT * FROM products').all() as (ProductRow & {
    mrp: number;
    ptr: number;
    pts: number;
  })[];

  const insert = db.prepare(
    `INSERT OR IGNORE INTO distributor_products
       (distributor_id, product_id, ptr, pts, mrp, scheme_buy_qty, scheme_free_qty,
        discount_pct, available_qty, min_order_qty, status)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'ACTIVE')`,
  );

  let count = 0;
  db.transaction(() => {
    for (const distributor of distributorIds) {
      // Each distributor carries 55-90% of the catalogue.
      const coverage = between(0.55, 0.9);
      for (const product of products) {
        if (!chance(coverage)) continue;

        // Distributors compete within a few percent of the reference PTR.
        const ptr = round2(product.ptr * between(0.93, 1.07));
        const pts = round2(ptr * between(0.88, 0.95));
        const scheme = pickScheme();
        // A discount and a free-goods scheme rarely appear together in trade.
        const discountPct = scheme.buy === 0 && chance(0.28) ? round2(between(2, 8)) : 0;

        // Availability: most lines stocked, some thin, a few out.
        const availability = rand();
        const availableQty =
          availability < 0.08 ? 0 : availability < 0.2 ? intBetween(5, 40) : intBetween(60, 900);

        insert.run(
          distributor,
          product.id,
          ptr,
          pts,
          product.mrp,
          scheme.buy,
          scheme.free,
          discountPct,
          availableQty,
          pick([1, 1, 1, 5, 10]),
        );
        count += 1;
      }
    }
  })();

  // Every product should have at least one well-stocked source, otherwise the
  // Replenishment Center recommends nothing and the demo looks broken.
  const orphaned = db
    .prepare(
      `SELECT p.id, p.ptr, p.mrp FROM products p
        WHERE NOT EXISTS (SELECT 1 FROM distributor_products dp
                           WHERE dp.product_id = p.id AND dp.available_qty > 50)`,
    )
    .all() as { id: number; ptr: number; mrp: number }[];

  db.transaction(() => {
    for (const product of orphaned) {
      const distributor = pick(distributorIds.slice(0, 8));
      const scheme = pickScheme();
      db.prepare(
        `INSERT INTO distributor_products
           (distributor_id, product_id, ptr, pts, mrp, scheme_buy_qty, scheme_free_qty,
            discount_pct, available_qty, min_order_qty, status)
         VALUES (?, ?, ?, ?, ?, ?, ?, 0, ?, 1, 'ACTIVE')
         ON CONFLICT (distributor_id, product_id) DO UPDATE SET available_qty = excluded.available_qty`,
      ).run(
        distributor,
        product.id,
        round2(product.ptr * between(0.95, 1.03)),
        round2(product.ptr * 0.92),
        product.mrp,
        scheme.buy,
        scheme.free,
        intBetween(150, 800),
      );
      count += 1;
    }
  })();

  // Point each product at its cheapest source by effective cost.
  db.exec(`
    UPDATE products SET preferred_distributor_id = (
      SELECT dp.distributor_id FROM distributor_products dp
       WHERE dp.product_id = products.id AND dp.available_qty > 0
       ORDER BY dp.ptr * (1 - dp.discount_pct / 100.0)
                / (1.0 + CAST(dp.scheme_free_qty AS REAL) / MAX(dp.scheme_buy_qty, 1))
       LIMIT 1
    )
  `);

  return count;
}

/**
 * Purchase-order history, so the procurement screens are not empty on first run.
 *
 * Orders are placed at intervals across the last 90 days and taken through the
 * real service functions - createPurchaseOrder() and receivePurchaseOrder() -
 * so the generated history exercises the actual scheme arithmetic, batch
 * creation and invoice raising rather than fabricating rows.
 */
function seedPurchaseOrders(adminId: number): { orders: number; received: number; payments: number } {
  const db = getDb();
  const distributors = db
    .prepare("SELECT id FROM distributors WHERE status = 'ACTIVE' ORDER BY distance_km LIMIT 12")
    .all() as { id: number }[];

  let orders = 0;
  let received = 0;
  let payments = 0;

  for (let dayOffset = 88; dayOffset >= 0; dayOffset -= 7) {
    const poDate = addDays(today(), -dayOffset);
    const distributor = pick(distributors);

    // Pick products this distributor actually stocks.
    const lines = db
      .prepare(
        `SELECT dp.product_id, dp.min_order_qty, dp.available_qty
         FROM distributor_products dp
         WHERE dp.distributor_id = ? AND dp.available_qty > 100
         ORDER BY RANDOM() LIMIT ?`,
      )
      .all(distributor.id, intBetween(3, 8)) as {
      product_id: number;
      min_order_qty: number;
      available_qty: number;
    }[];
    if (lines.length === 0) continue;

    try {
      const po = createPurchaseOrder({
        distributor_id: distributor.id,
        po_date: poDate,
        user_id: adminId,
        username: 'admin',
        status: 'SENT',
        items: lines.map((line) => ({
          product_id: line.product_id,
          quantity: Math.max(line.min_order_qty, intBetween(20, 120)),
        })),
      });
      orders += 1;

      // Older orders are received; the two most recent stay open so the
      // Purchase Orders screen shows work in progress.
      if (dayOffset > 14) {
        const receiptDate = addDays(poDate, intBetween(1, 4));
        receivePurchaseOrder({
          po_id: po.id,
          receipt_date: receiptDate,
          invoice_number: `INV/${poDate.slice(2, 4)}${poDate.slice(5, 7)}/${intBetween(1000, 9999)}`,
          user_id: adminId,
          username: 'admin',
          items: po.items.map((item) => ({
            po_item_id: Number(item.id),
            received_qty: Number(item.ordered_qty),
            batch_number: `PB${poDate.replace(/-/g, '').slice(2)}${intBetween(100, 999)}`,
            expiry_date: addDays(receiptDate, intBetween(400, 900)),
            manufacturing_date: addDays(receiptDate, -intBetween(30, 150)),
          })),
        });
        received += 1;
      } else if (dayOffset > 7) {
        db.prepare("UPDATE purchase_orders SET status = 'CONFIRMED' WHERE id = ?").run(po.id);
      }
    } catch {
      // A minimum-order-value rule can legitimately reject a small basket.
      // Skipping is the correct outcome, not an error to hide.
    }
  }

  // Settle roughly two thirds of the invoices raised, leaving a realistic
  // outstanding balance with some of it overdue.
  const invoices = db
    .prepare("SELECT id, distributor_id, invoice_amount FROM supplier_invoices WHERE status = 'UNPAID' ORDER BY id")
    .all() as { id: number; distributor_id: number; invoice_amount: number }[];

  for (const invoice of invoices) {
    if (!chance(0.62)) continue;
    try {
      // Some payments are partial - that is what produces a PARTIAL status.
      const amount = chance(0.75) ? invoice.invoice_amount : round2(invoice.invoice_amount * between(0.3, 0.7));
      recordSupplierPayment({
        distributor_id: invoice.distributor_id,
        invoice_id: invoice.id,
        amount,
        method: pick(['BANK', 'UPI', 'CHEQUE', 'CASH'] as const),
        user_id: adminId,
        username: 'admin',
      });
      payments += 1;
    } catch {
      /* rounding can make a full-value payment marginally exceed the balance */
    }
  }

  return { orders, received, payments };
}

/** Marks historic credit sales as unsettled so customer outstanding is non-empty. */
function seedCustomerCredit(): number {
  const db = getDb();
  // Institutional buyers are the realistic credit customers.
  const sales = db
    .prepare(
      `SELECT s.id, s.total, s.sale_date FROM sales s
       JOIN customers c ON c.id = s.customer_id
       WHERE c.customer_type = 'INSTITUTIONAL' AND s.status <> 'CANCELLED'
         AND date(s.sale_date) >= date('now', '-75 days')
       ORDER BY s.sale_date DESC LIMIT 60`,
    )
    .all() as { id: number; total: number; sale_date: string }[];

  let count = 0;
  db.transaction(() => {
    for (const sale of sales) {
      if (!chance(0.55)) continue;
      // Some fully unpaid, some part-paid.
      const paid = chance(0.4) ? round2(sale.total * between(0.2, 0.6)) : 0;
      db.prepare(
        "UPDATE sales SET payment_method = 'CREDIT', paid_amount = ?, due_date = ? WHERE id = ?",
      ).run(paid, addDays(sale.sale_date.slice(0, 10), 30), sale.id);
      count += 1;
    }
  })();
  return count;
}

