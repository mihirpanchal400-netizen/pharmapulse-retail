function seedManufacturers(): void {
  const db = getDb();
  const names = (
    db
      .prepare("SELECT DISTINCT manufacturer AS name FROM products WHERE manufacturer IS NOT NULL AND manufacturer <> ''")
      .all() as { name: string }[]
  ).map((r) => r.name);

  const insert = db.prepare(
    'INSERT OR IGNORE INTO manufacturers (name, code, contact_person, phone, email) VALUES (?, ?, ?, ?, ?)',
  );

  db.transaction(() => {
    names.forEach((name, i) => {
      insert.run(
        name,
        `MFR-${String(i + 1).padStart(3, '0')}`,
        `${pick(FIRST_NAMES)} ${pick(LAST_NAMES)}`,
        `+91 22 ${intBetween(20000000, 49999999)}`,
        `contact@${name.toLowerCase().replace(/[^a-z]/g, '').slice(0, 12)}-demo.test`,
      );
    });
  })();

  // Link products to their manufacturer record.
  db.exec(`
    UPDATE products
       SET manufacturer_id = (SELECT m.id FROM manufacturers m WHERE m.name = products.manufacturer)
     WHERE manufacturer IS NOT NULL
  `);
}

