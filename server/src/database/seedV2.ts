/**
 * SEED v2 - DEMO DISTRIBUTOR NETWORK AND PROCUREMENT HISTORY
 * ==========================================================
 *
 * Generates the buying side of the pharmacy on top of the v1 trading history.
 *
 * EVERYTHING HERE IS SYNTHETIC.
 *
 * The distributors are invented. Their catalogues, prices, schemes and stock
 * figures are generated by the arithmetic in this file. Nothing is scraped
 * from, downloaded from, or connected to Retailio, Pharmarack, or any other
 * commercial platform, and no figure here represents real market data.
 *
 * Deterministic: a fixed PRNG seed means `npm run seed` reproduces the same
 * network every time, so a rehearsed demo shows the same numbers on the day.
 */

const SEED = 20260820;

function mulberry32(seed: number) {
  let a = seed >>> 0;
  return function random(): number {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(SEED);
const between = (min: number, max: number) => min + rand() * (max - min);
const intBetween = (min: number, max: number) => Math.floor(between(min, max + 1));
const pick = <T>(arr: readonly T[]): T => arr[Math.floor(rand() * arr.length)];
const chance = (p: number) => rand() < p;

